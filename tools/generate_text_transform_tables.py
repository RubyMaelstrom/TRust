#!/usr/bin/env python3
"""Generate CSS text-transform mappings from official, downloaded sources.

No network access. Usage: this-script UCD-DIRECTORY CSS-TEXT-4 MATH-ITALIC-TABLE
UCD files: https://www.unicode.org/Public/17.0.0/ucd/{UnicodeData,SpecialCasing}.txt
CSS/MathML sources: the local web-standards library (revisions in output).
"""

import hashlib
from pathlib import Path
import re
import sys


def scalar(value):
    return f"'\\u{{{value:x}}}'"


def string(values):
    return '"' + ''.join(f'\\u{{{value:x}}}' for value in values) + '"'


def generate(ucd, css, math):
    upper, title, width = {}, {}, {}
    for line in (ucd / 'UnicodeData.txt').read_text().splitlines():
        fields = line.split(';')
        cp = int(fields[0], 16)
        upper[cp] = [int(fields[12], 16)] if fields[12] else [cp]
        title[cp] = [int(fields[14], 16)] if fields[14] else upper[cp]
        decomposition = fields[5].split()
        if decomposition and decomposition[0] in ('<wide>', '<narrow>'):
            assert len(decomposition) == 2
            other = int(decomposition[1], 16)
            source, target = (other, cp) if decomposition[0] == '<wide>' else (cp, other)
            width[source] = target
    for line in (ucd / 'SpecialCasing.txt').read_text().splitlines():
        fields = [value.strip() for value in line.split('#')[0].split(';')]
        if len(fields) >= 5 and not fields[4]:
            cp = int(fields[0], 16)
            title[cp] = [int(value, 16) for value in fields[2].split()]
            upper[cp] = [int(value, 16) for value in fields[3].split()]
    appendix = css.read_text().split('<h2 id="small-kana"')[1].split('<h2 id="word-phrase-detection"')[0]
    appendix = re.sub(r'<!--.*?-->', '', appendix, flags=re.S)
    kana = [int(value, 16) for value in re.findall(r'<td>&#x([0-9A-Fa-f]+);', appendix)]
    assert len(kana) % 2 == 0
    italic = dict((int(a, 16), int(b, 16)) for a, b in re.findall(
        r'<td>&#x([0-9A-Fa-f]+);[^<]*</td><td>&#x([0-9A-Fa-f]+);', math.read_text()))
    out = ['//! Generated by tools/generate_text_transform_tables.py; do not edit.',
           '//! Unicode 17.0.0; Unicode data license: transform_data.LICENSE.',
           '//! CSSWG 81c27f686901 #small-kana; MathML Core f69212ad1f21 #italic-mappings.']
    for file in [ucd / 'UnicodeData.txt', ucd / 'SpecialCasing.txt', css, math]:
        out.append(f'//! {file.name} SHA-256: {hashlib.sha256(file.read_bytes()).hexdigest()}')
    out += ['', 'pub(super) static TITLE: &[(char, &str)] = &[']
    out += [f'    ({scalar(cp)}, {string(mapping)}),' for cp, mapping in sorted(title.items()) if mapping != upper[cp]]
    out += ['];', '']
    for name, mapping in [('WIDTH', width), ('KANA', dict(zip(kana[::2], kana[1::2]))), ('MATH', italic)]:
        out += [f'pub(super) static {name}: &[(char, char)] = &[']
        out += [f'    ({scalar(cp)}, {scalar(target)}),' for cp, target in sorted(mapping.items())]
        out += ['];', '']
    return '\n'.join(out)


if __name__ == '__main__':
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    output = Path(__file__).resolve().parents[1] / 'src/text/transform_data.rs'
    output.write_text(generate(*map(Path, sys.argv[1:])))
