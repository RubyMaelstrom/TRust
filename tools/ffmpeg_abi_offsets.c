/*
 * Prints the byte offsets of the AVFrame, AVPacket and AVCodecParameters
 * members that ffmpeg-dl mirrors, plus the AVChannelLayout member it reads,
 * as laid out by the *official public headers* of one FFmpeg release.
 *
 * The layout tests in abi.rs compare their offset_of! values with this
 * output (LP64 targets). To re-verify against a release:
 *
 *   git clone --depth 1 --branch n8.0.3 https://github.com/FFmpeg/FFmpeg ffmpeg-n8.0.3
 *   mkdir -p stub-include/libavutil
 *   printf '#define AV_HAVE_BIGENDIAN 0\n#define AV_HAVE_FAST_UNALIGNED 1\n' \
 *       > stub-include/libavutil/avconfig.h        # generated by ./configure
 *   cc -I ffmpeg-n8.0.3 -I stub-include abi_offsets.c -o abi_offsets && ./abi_offsets
 *
 * Which members exist is decided by the headers' FF_API_* macros, which in
 * every release depend only on the library major version, so the output is
 * identical for every minor/micro release of one major.
 */
#include <stddef.h>
#include <stdio.h>
#include <libavutil/frame.h>
#include <libavutil/channel_layout.h>
#include <libavcodec/avcodec.h>
#include <libavcodec/codec_par.h>
#include <libavcodec/packet.h>
#include <libavcodec/codec_desc.h>

#define F(t, m) printf("%s.%s = %zu\n", #t, #m, offsetof(t, m))

int main(void) {
    printf("# avcodec %d.%d.%d avutil %d.%d.%d\n", LIBAVCODEC_VERSION_MAJOR, LIBAVCODEC_VERSION_MINOR,
           LIBAVCODEC_VERSION_MICRO, LIBAVUTIL_VERSION_MAJOR, LIBAVUTIL_VERSION_MINOR, LIBAVUTIL_VERSION_MICRO);
    F(AVFrame, data); F(AVFrame, linesize); F(AVFrame, extended_data);
    F(AVFrame, width); F(AVFrame, height); F(AVFrame, nb_samples); F(AVFrame, format);
#if LIBAVUTIL_VERSION_MAJOR < 60
    F(AVFrame, key_frame);
#endif
    F(AVFrame, pict_type); F(AVFrame, sample_aspect_ratio); F(AVFrame, pts); F(AVFrame, pkt_dts);
    F(AVFrame, time_base);
#if LIBAVUTIL_VERSION_MAJOR < 59
    F(AVFrame, coded_picture_number); F(AVFrame, display_picture_number);
#endif
    F(AVFrame, quality); F(AVFrame, opaque); F(AVFrame, repeat_pict);
#if LIBAVUTIL_VERSION_MAJOR < 60
    F(AVFrame, interlaced_frame); F(AVFrame, top_field_first); F(AVFrame, palette_has_changed);
#endif
#if LIBAVUTIL_VERSION_MAJOR < 59
    F(AVFrame, reordered_opaque);
#endif
    F(AVFrame, sample_rate);
#if LIBAVUTIL_VERSION_MAJOR < 59
    F(AVFrame, channel_layout);
#endif
    F(AVFrame, buf); F(AVFrame, extended_buf); F(AVFrame, nb_extended_buf);
    F(AVFrame, side_data); F(AVFrame, nb_side_data); F(AVFrame, flags);
    F(AVFrame, color_range); F(AVFrame, color_primaries); F(AVFrame, color_trc);
    F(AVFrame, colorspace); F(AVFrame, chroma_location); F(AVFrame, best_effort_timestamp);
#if LIBAVUTIL_VERSION_MAJOR < 60
    F(AVFrame, pkt_pos);
#endif
#if LIBAVUTIL_VERSION_MAJOR < 59
    F(AVFrame, pkt_duration);
#endif
    F(AVFrame, metadata); F(AVFrame, decode_error_flags);
#if LIBAVUTIL_VERSION_MAJOR < 59
    F(AVFrame, channels);
#endif
#if LIBAVUTIL_VERSION_MAJOR < 60
    F(AVFrame, pkt_size);
#endif
    F(AVFrame, hw_frames_ctx); F(AVFrame, opaque_ref);
    F(AVFrame, crop_top); F(AVFrame, crop_bottom); F(AVFrame, crop_left); F(AVFrame, crop_right);
    F(AVFrame, private_ref);
#if LIBAVUTIL_VERSION_MAJOR > 57 || LIBAVUTIL_VERSION_MINOR >= 24
    F(AVFrame, ch_layout); F(AVChannelLayout, nb_channels);
#endif
    F(AVPacket, buf); F(AVPacket, pts); F(AVPacket, dts); F(AVPacket, data); F(AVPacket, size);
    F(AVPacket, stream_index); F(AVPacket, flags);
    F(AVCodecParameters, codec_type); F(AVCodecParameters, codec_id); F(AVCodecParameters, codec_tag);
    F(AVCodecParameters, extradata); F(AVCodecParameters, extradata_size);
    F(AVCodecDescriptor, id);
    return 0;
}
