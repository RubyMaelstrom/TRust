/// One <grid-line> (CSS Grid 2 #line-placement). Names are case-sensitive.
#[derive(Clone, Debug, PartialEq)]
enum LineRaw {
    Auto,
    Index(i32),
    Span(usize),
    Name(String),
    NamedIndex(String, i32),
    NamedSpan(String, usize),
}

fn parse_grid_line(v: Option<&str>) -> LineRaw {
    let Some(v) = v.map(str::trim).filter(|v| !v.is_empty()) else {
        return LineRaw::Auto;
    };
    if v.eq_ignore_ascii_case("auto") {
        return LineRaw::Auto;
    }
    let mut span = false;
    let mut number = None;
    let mut name = None;
    for part in v.split_whitespace() {
        if part.eq_ignore_ascii_case("span") {
            if span {
                return LineRaw::Auto;
            }
            span = true;
        } else if let Ok(n) = part.parse::<i32>() {
            if number.is_some() || n == 0 {
                return LineRaw::Auto;
            }
            number = Some(n.clamp(-1000, 1000));
        } else {
            if name.is_some() || part.eq_ignore_ascii_case("auto") {
                return LineRaw::Auto;
            }
            name = Some(part.to_string());
        }
    }
    match (span, number, name) {
        (true, Some(n), _) if n < 1 => LineRaw::Auto,
        (true, n, Some(name)) => LineRaw::NamedSpan(name, n.unwrap_or(1) as usize),
        (true, Some(n), None) => LineRaw::Span(n as usize),
        (true, None, None) => LineRaw::Auto,
        (false, Some(n), Some(name)) => LineRaw::NamedIndex(name, n),
        (false, None, Some(name)) => LineRaw::Name(name),
        (false, Some(n), None) => LineRaw::Index(n),
        _ => LineRaw::Auto,
    }
}

/// Extract line-name sets alongside the already expanded track list. Repeated
/// boundaries merge names; the final boundary is retained as well. Grid 2
/// #named-lines, #repeat-notation and #implicit-named-lines.
fn template_line_names(value: &str, tracks: usize) -> Vec<Vec<String>> {
    let mut names = vec![Vec::new(); tracks + 1];
    let parts = named_track_tokens(value);
    let count_tracks = |text: &str| split_track_tokens(text).len();
    let fixed: usize = parts
        .iter()
        .filter_map(|part| {
            if part.starts_with('[') {
                return Some(0);
            }
            if part.to_ascii_lowercase().starts_with("repeat(") {
                let (count, list) = part[7..part.len() - 1].split_once(',')?;
                return Some(
                    count.trim().parse::<usize>().unwrap_or(0).min(1000) * count_tracks(list),
                );
            }
            Some(1)
        })
        .sum();
    let mut line = 0;
    let append = |part: &str, line: &mut usize, names: &mut Vec<Vec<String>>| {
        if let Some(group) = part.strip_prefix('[').and_then(|v| v.strip_suffix(']')) {
            if let Some(current) = names.get_mut(*line) {
                for name in group.split_whitespace() {
                    if !current.iter().any(|n| n == name) {
                        current.push(name.to_owned());
                    }
                }
            }
        } else {
            *line += 1;
        }
    };
    for part in parts {
        if part.to_ascii_lowercase().starts_with("repeat(") && part.ends_with(')') {
            let Some((count, list)) = part[7..part.len() - 1].split_once(',') else {
                continue;
            };
            let count = count
                .trim()
                .parse::<usize>()
                .unwrap_or_else(|_| tracks.saturating_sub(fixed) / count_tracks(list).max(1))
                .min(1000);
            let repeated = named_track_tokens(list);
            for _ in 0..count {
                for part in &repeated {
                    append(part, &mut line, &mut names);
                }
                if line > tracks {
                    break;
                }
            }
        } else {
            append(part, &mut line, &mut names);
        }
    }
    names
}

fn named_track_tokens(value: &str) -> Vec<&str> {
    let mut parts = Vec::new();
    let mut start = 0;
    let mut parens = 0;
    let mut bracket = false;
    let mut escaped = false;
    for (i, c) in value.char_indices() {
        if escaped {
            escaped = false;
            continue;
        }
        if c == '\\' {
            escaped = true;
            continue;
        }
        match c {
            '(' => parens += 1,
            ')' => parens -= 1,
            '[' if parens == 0 => {
                if start < i && !value[start..i].trim().is_empty() {
                    parts.push(value[start..i].trim());
                }
                start = i;
                bracket = true;
            }
            ']' if parens == 0 => {
                parts.push(&value[start..i + 1]);
                start = i + 1;
                bracket = false;
            }
            c if c.is_whitespace() && parens == 0 && !bracket => {
                if start < i {
                    parts.push(&value[start..i]);
                }
                start = i + c.len_utf8();
            }
            _ => {}
        }
    }
    if start < value.len() {
        parts.push(&value[start..]);
    }
    parts
}

#[derive(Clone, Copy, Debug)]
struct AxisPlace {
    /// Signed until implicit tracks before the explicit grid are allocated.
    start: Option<i32>,
    span: usize,
}

fn resolve_axis(
    start: LineRaw,
    end: LineRaw,
    explicit_tracks: usize,
    names: &[Vec<String>],
) -> AxisPlace {
    let explicit_end = explicit_tracks as i32;
    let has = |line: i32, name: &str| {
        line >= 0
            && names
                .get(line as usize)
                .is_some_and(|v| v.iter().any(|n| n == name))
    };
    let nth = |name: &str, number: i32| {
        let step = if number < 0 { -1 } else { 1 };
        let mut left = number.unsigned_abs();
        let mut line = if step < 0 { explicit_end } else { 0 };
        loop {
            if line < 0 || line > explicit_end || has(line, name) {
                left -= 1;
            }
            if left == 0 {
                break line;
            }
            line += step;
        }
    };
    let index = |raw: &LineRaw, end: bool| match raw {
        LineRaw::Index(n) => Some(if *n > 0 { n - 1 } else { explicit_end + 1 + n }),
        LineRaw::NamedIndex(name, n) => Some(nth(name, *n)),
        LineRaw::Name(name) => {
            let edge = format!("{name}-{}", if end { "end" } else { "start" });
            Some(
                (0..=explicit_end)
                    .find(|&line| has(line, &edge))
                    .unwrap_or_else(|| nth(name, 1)),
            )
        }
        _ => None,
    };
    let span_to = |from: i32, raw: &LineRaw, step: i32| {
        let (mut left, name) = match raw {
            LineRaw::Span(n) => (*n, None),
            LineRaw::NamedSpan(name, n) => (*n, Some(name.as_str())),
            _ => (1, None),
        };
        let mut line = from;
        while left > 0 {
            line += step;
            if name.is_none_or(|name| {
                has(line, name) || step > 0 && line > explicit_end || step < 0 && line < 0
            }) {
                left -= 1;
            }
        }
        line
    };
    let (a, b) = match (index(&start, false), index(&end, true)) {
        (Some(a), Some(b)) if a == b => (a, a + 1),
        (Some(a), Some(b)) => (a.min(b), a.max(b)),
        (Some(a), None) => (a, span_to(a, &end, 1)),
        (None, Some(b)) => (span_to(b, &start, -1), b),
        (None, None) => {
            let span = match start {
                LineRaw::Span(n) => n,
                LineRaw::NamedSpan(_, _) => 1,
                _ => match end {
                    LineRaw::Span(n) => n,
                    _ => 1,
                },
            };
            return AxisPlace { start: None, span };
        }
    };
    AxisPlace {
        start: Some(a),
        span: (b - a).max(1) as usize,
    }
}

/// The dynamic occupancy grid for §8.5 (rows grow as needed).
struct Occ {
    cols: usize,
    rows: Vec<Vec<bool>>,
}

impl Occ {
    fn free(&self, r: usize, c: usize, rs: usize, cs: usize) -> bool {
        if c + cs > self.cols {
            return false;
        }
        for rr in r..r + rs {
            let Some(row) = self.rows.get(rr) else {
                continue; // beyond current rows: empty
            };
            if row[c..(c + cs).min(self.cols)].iter().any(|&b| b) {
                return false;
            }
        }
        true
    }

    fn mark(&mut self, r: usize, c: usize, rs: usize, cs: usize) {
        while self.rows.len() < r + rs {
            self.rows.push(vec![false; self.cols]);
        }
        for rr in r..r + rs {
            for cell in self.rows[rr][c..(c + cs).min(self.cols)].iter_mut() {
                *cell = true;
            }
        }
    }
}

/// A fully placed item: 0-based track ranges in both axes.
#[derive(Clone, Debug)]
pub(crate) struct Placed {
    pub cols: Range<usize>,
    pub rows: Range<usize>,
}

/// §8.5, written (like the spec) for row flow; `row_flow == false` swaps
/// the axes on entry and exit. `dense` resets the search to the grid start
/// per item.
fn auto_place(
    mut items: Vec<(AxisPlace, AxisPlace)>, // (col, row) per item
    explicit_cols: usize,
    row_flow: bool,
    dense: bool,
) -> Vec<Placed> {
    if !row_flow {
        for (c, r) in &mut items {
            std::mem::swap(c, r);
        }
    }
    // Step 3: the implicit grid's column count.
    let mut cols = explicit_cols.max(1);
    for (c, _) in &items {
        if let Some(s) = c.start.map(|n| n as usize) {
            cols = cols.max(s + c.span);
        } else {
            cols = cols.max(c.span);
        }
    }
    let mut occ = Occ {
        cols,
        rows: Vec::new(),
    };
    let mut out: Vec<Option<Placed>> = vec![None; items.len()];
    // Step 1: definite positions in both axes.
    for (i, (c, r)) in items.iter().enumerate() {
        if let (Some(cs), Some(rs)) = (c.start.map(|n| n as usize), r.start.map(|n| n as usize)) {
            occ.mark(rs, cs, r.span, c.span);
            out[i] = Some(Placed {
                cols: cs..cs + c.span,
                rows: rs..rs + r.span,
            });
        }
    }
    // Step 2: items locked to a definite row.
    let mut row_cursor: std::collections::HashMap<usize, usize> = std::collections::HashMap::new();
    for (i, (c, r)) in items.iter().enumerate() {
        if out[i].is_some() || c.start.is_some() || r.start.is_none() {
            continue;
        }
        let rs = r.start.unwrap() as usize;
        let from = if dense {
            0
        } else {
            *row_cursor.get(&rs).unwrap_or(&0)
        };
        let mut cc = from;
        while !occ.free(rs, cc, r.span, c.span) {
            cc += 1;
            if cc + c.span > occ.cols {
                // No room in the row: overlap is not allowed here; grow
                // columns only for span overflow (kept within the row).
                cc = occ.cols.saturating_sub(c.span);
                break;
            }
        }
        occ.mark(rs, cc, r.span, c.span);
        row_cursor.insert(rs, cc + c.span);
        out[i] = Some(Placed {
            cols: cc..cc + c.span,
            rows: rs..rs + r.span,
        });
    }
    // Step 4: the auto-placement cursor.
    let (mut cur_r, mut cur_c) = (0usize, 0usize);
    for (i, (c, r)) in items.iter().enumerate() {
        if out[i].is_some() {
            continue;
        }
        if dense {
            cur_r = 0;
            cur_c = 0;
        }
        let (rs, cs) = if let Some(cs) = c.start.map(|n| n as usize) {
            // Definite column: walk rows at that column.
            if dense {
                cur_r = 0;
            } else if cs < cur_c {
                cur_r += 1;
            }
            let mut rr = cur_r;
            while !occ.free(rr, cs, r.span, c.span) {
                rr += 1;
            }
            (rr, cs)
        } else {
            // Fully auto: scan columns, overflow to the next row.
            loop {
                if cur_c + c.span <= occ.cols && occ.free(cur_r, cur_c, r.span, c.span) {
                    break (cur_r, cur_c);
                }
                if cur_c + c.span >= occ.cols {
                    cur_r += 1;
                    cur_c = 0;
                } else {
                    cur_c += 1;
                }
            }
        };
        occ.mark(rs, cs, r.span, c.span);
        cur_r = rs;
        cur_c = cs; // sparse flow continues from here
        out[i] = Some(Placed {
            cols: cs..cs + c.span,
            rows: rs..rs + r.span,
        });
    }
    let mut placed: Vec<Placed> = out.into_iter().map(Option::unwrap).collect();
    if !row_flow {
        for p in &mut placed {
            std::mem::swap(&mut p.cols, &mut p.rows);
        }
    }
    placed
}

/// `name → (row range, column range)` of the named areas.
type AreaMap = std::collections::HashMap<String, (Range<usize>, Range<usize>)>;

/// Parse `grid-template-areas` (§7.3) into the area map plus the template's
/// row/column counts. Non-rectangular or ragged definitions invalidate the
/// whole declaration.
fn parse_areas(value: &str) -> Option<(AreaMap, usize, usize)> {
    let v = value.trim();
    if v.is_empty() || v.eq_ignore_ascii_case("none") {
        return None;
    }
    // Row strings are quoted; tokenize each into cell names / null cells.
    let mut rows: Vec<Vec<String>> = Vec::new();
    let mut rest = v;
    while let Some(q) = rest.find(['"', '\'']) {
        let quote = rest.as_bytes()[q] as char;
        let tail = &rest[q + 1..];
        let end = tail.find(quote)?;
        let row: Vec<String> = tail[..end]
            .split_whitespace()
            .map(|t| t.to_string())
            .collect();
        if !row.is_empty() {
            rows.push(row);
        }
        rest = &tail[end + 1..];
    }
    if rows.is_empty() {
        return None;
    }
    let ncols = rows[0].len();
    if rows.iter().any(|r| r.len() != ncols) {
        return None; // ragged
    }
    let mut map: AreaMap = std::collections::HashMap::new();
    for (r, row) in rows.iter().enumerate() {
        for (c, name) in row.iter().enumerate() {
            if name.starts_with('.') {
                continue; // null cell
            }
            let key = name.clone();
            match map.get_mut(&key) {
                None => {
                    map.insert(key, (r..r + 1, c..c + 1));
                }
                Some((rr, cc)) => {
                    rr.start = rr.start.min(r);
                    rr.end = rr.end.max(r + 1);
                    cc.start = cc.start.min(c);
                    cc.end = cc.end.max(c + 1);
                }
            }
        }
    }
    // Rectangularity: every named area's cells must exactly tile its rect.
    for (name, (rr, cc)) in &map {
        for r in rr.clone() {
            for c in cc.clone() {
                if rows[r][c] != *name {
                    return None;
                }
            }
        }
    }
    Some((map, rows.len(), ncols))
}

