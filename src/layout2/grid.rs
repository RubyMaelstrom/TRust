/// An item's contribution to the tracks it spans in one axis.
#[derive(Clone)]
struct Contrib {
    tracks: Range<usize>,
    /// §11.5's minimum contribution, distinct from min-content when the
    /// item can shrink (e.g. min-width:0 or scrollable overflow).
    minimum: f32,
    min: f32,
    max: f32,
}

struct GridSetup<'t> {
    ordered: Vec<&'t BoxNode>,
    cols: Vec<Track>,
    rows: Vec<Track>,
    placed: Vec<Placed>,
    row_names: Vec<Vec<String>>,
    gap_col: f32,
    gap_row: f32,
    inherited: Option<RowInput>,
}

/// Per-transaction parent constraints, never retained across layouts. A subgrid
/// is NOT an independent formatting context (#subgrid-items): its descendants'
/// contributions travel up, and the resulting track positions travel down.
#[derive(Default)]
pub(super) struct SubgridRows {
    inputs: std::collections::HashMap<NodeId, RowInput>,
    contributions: std::collections::HashMap<NodeId, Vec<Contrib>>,
}

impl SubgridRows {
    pub(super) fn active(&self) -> bool {
        !self.inputs.is_empty()
    }
    pub(super) fn contains(&self, node: NodeId) -> bool {
        self.inputs.contains_key(&node)
    }
}

#[derive(Clone)]
struct RowInput {
    tracks: Vec<Track>,
    names: Vec<Vec<String>>,
    // None during intrinsic measurement; exact parent positions on final layout.
    positions: Option<Vec<f32>>,
    gap: f32,
    start_edge: f32,
    end_edge: f32,
}

impl RowInput {
    fn export(&self, mut items: Vec<Contrib>, gap: f32) -> Vec<Contrib> {
        let n = self.tracks.len();
        let difference = (gap - self.gap) / 2.0;
        // #subgrid-margins and #subgrid-gaps: accumulate edge decorations and
        // half the gutter difference as an extra layer of item margin.
        for item in &mut items {
            let before = if item.tracks.start == 0 {
                self.start_edge
            } else {
                difference
            };
            let after = if item.tracks.end == n {
                self.end_edge
            } else {
                difference
            };
            item.minimum += before + after;
            item.min += before + after;
            item.max += before + after;
        }
        // #subgrid-edge-placeholders: decorations still contribute when empty
        // tracks separate an occupied track from the subgrid's edge.
        for start in [true, false] {
            let Some(edge) = items
                .iter()
                .map(|c| if start { c.tracks.start } else { c.tracks.end })
                .reduce(|a, b| if start { a.min(b) } else { a.max(b) })
            else {
                continue;
            };
            if (start && edge == 0) || (!start && edge == n) {
                continue;
            }
            let extra = if start {
                self.start_edge
            } else {
                self.end_edge
            } - difference;
            let placeholders: Vec<_> = items
                .iter()
                .filter(|c| {
                    if start {
                        c.tracks.start == edge
                    } else {
                        c.tracks.end == edge
                    }
                })
                .map(|c| Contrib {
                    tracks: if start {
                        0..c.tracks.end
                    } else {
                        c.tracks.start..n
                    },
                    minimum: c.minimum + extra,
                    min: c.min + extra,
                    max: c.max + extra,
                })
                .collect();
            items.extend(placeholders);
        }
        if items.is_empty() && n > 0 {
            items.push(Contrib {
                tracks: 0..n,
                minimum: self.start_edge + self.end_edge,
                min: self.start_edge + self.end_edge,
                max: self.start_edge + self.end_edge,
            });
        }
        items
    }

    fn resolved(&self, gap: f32) -> Option<(Vec<Track>, Vec<f32>)> {
        let positions = self.positions.as_ref()?;
        let mut tracks = self.tracks.clone();
        let mut local = Vec::with_capacity(tracks.len());
        let difference = (gap - self.gap) / 2.0;
        let n = tracks.len();
        for (i, track) in tracks.iter_mut().enumerate() {
            let start = if i == 0 {
                0.0
            } else {
                positions[i] - self.start_edge + difference
            };
            let end = positions[i] + track.base
                - self.start_edge
                - if i + 1 == n {
                    self.end_edge
                } else {
                    difference
                };
            local.push(start);
            track.base = (end - start).max(0.0);
        }
        Some((tracks, local))
    }
}

/// CSS Grid 2 #resolved-track-list-subgrid: serialize local line names, not
/// inherited pixel sizes. Empty trailing name sets expose the used span.
pub(crate) fn serialize_subgrid_rows(value: &str, tracks: usize) -> String {
    fn names(value: &str) -> Vec<String> {
        let mut result = Vec::new();
        let mut rest = value;
        while let Some(start) = rest.find('[') {
            let tail = &rest[start + 1..];
            let Some(end) = tail.find(']') else { break };
            result.push(format!(
                "[{}]",
                tail[..end].split_whitespace().collect::<Vec<_>>().join(" ")
            ));
            rest = &tail[end + 1..];
        }
        result
    }
    let mut parts: Vec<(usize, bool, Vec<String>)> = Vec::new();
    let mut rest = value.strip_prefix("subgrid").unwrap_or("").trim();
    while !rest.is_empty() {
        if rest.starts_with('[') {
            let Some(end) = rest.find(']') else { break };
            parts.push((1, false, names(&rest[..end + 1])));
            rest = rest[end + 1..].trim_start();
        } else if let Some(tail) = rest.strip_prefix("repeat(") {
            let Some(end) = tail.find(')') else { break };
            let Some((count, list)) = tail[..end].split_once(',') else {
                break;
            };
            let auto = count.trim() == "auto-fill";
            let count = if auto {
                0
            } else {
                count.trim().parse::<usize>().unwrap_or(0).min(1000)
            };
            parts.push((count, auto, names(list)));
            rest = tail[end + 1..].trim_start();
        } else {
            break;
        }
    }
    let lines = tracks + 1;
    let fixed = parts
        .iter()
        .filter(|(_, auto, _)| !*auto)
        .map(|(n, _, v)| n * v.len())
        .sum::<usize>();
    let mut result = Vec::new();
    for (count, auto, list) in parts {
        let count = if auto && !list.is_empty() {
            lines.saturating_sub(fixed) / list.len()
        } else {
            count
        };
        for _ in 0..count {
            result.extend(list.iter().cloned());
            if result.len() >= lines {
                break;
            }
        }
    }
    result.truncate(lines);
    result.resize(lines, "[]".to_owned());
    format!("subgrid {}", result.join(" "))
}

/// The §11 track sizing algorithm for one axis. `avail` is the definite
/// available grid space (content-box, this axis); `gap` the used gutter;
/// `stretch` whether the axis' content-distribution is normal/stretch
/// (§11.8). Contributions arrive pre-measured (margin-box).
fn size_tracks(
    tracks: &mut [Track],
    items: &[Contrib],
    avail: Option<f32>,
    gap: f32,
    stretch: bool,
) {
    size_tracks_constrained(tracks, items, avail, gap, stretch, false);
}

fn size_tracks_constrained(
    tracks: &mut [Track],
    items: &[Contrib],
    avail: Option<f32>,
    gap: f32,
    stretch: bool,
    min_content: bool,
) {
    let n_live = tracks.iter().filter(|t| !t.collapsed).count();
    let gaps_total = gap * (n_live.saturating_sub(1)) as f32;
    let track_avail = avail.map(|a| (a - gaps_total).max(0.0));

    // §11.4 initialize.
    for t in tracks.iter_mut() {
        if t.collapsed {
            t.base = 0.0;
            t.limit = 0.0;
            continue;
        }
        t.base = t.size.min.definite(track_avail).unwrap_or(0.0);
        t.limit = match &t.size.max {
            TrackFn::Fixed(l) => l
                .resolve(track_avail)
                .map(|v| v.max(0.0))
                .unwrap_or(f32::INFINITY),
            _ => f32::INFINITY,
        };
        if t.limit < t.base {
            t.limit = t.base;
        }
    }

    // Internal gap span helper: an item spanning k live tracks crosses
    // (k−1) gutters, which the spec treats as fixed tracks.
    let span_gaps = |r: &Range<usize>, tracks: &[Track]| -> f32 {
        let live = tracks[r.clone()].iter().filter(|t| !t.collapsed).count();
        gap * live.saturating_sub(1) as f32
    };

    // §11.5 resolve intrinsic track sizes, by ascending span, flexible-
    // track spanners last.
    let crosses_fr = |r: &Range<usize>, tracks: &[Track]| {
        tracks[r.clone()]
            .iter()
            .any(|t| matches!(t.size.max, TrackFn::Fr(_)))
    };
    let mut spans: Vec<usize> = items
        .iter()
        .filter(|c| !crosses_fr(&c.tracks, tracks))
        .map(|c| c.tracks.len())
        .collect();
    spans.sort_unstable();
    spans.dedup();
    for span in spans {
        let group: Vec<&Contrib> = items
            .iter()
            .filter(|c| c.tracks.len() == span && !crosses_fr(&c.tracks, tracks))
            .collect();
        if group.is_empty() {
            continue;
        }
        if span == 1 {
            // "Size tracks to fit non-spanning items."
            for c in &group {
                let ti = c.tracks.start;
                let t = &mut tracks[ti];
                if t.collapsed {
                    continue;
                }
                match &t.size.min {
                    TrackFn::Auto => t.base = t.base.max(c.minimum),
                    TrackFn::MinContent => t.base = t.base.max(c.min),
                    TrackFn::MaxContent => t.base = t.base.max(c.max),
                    _ => {}
                }
                match &t.size.max {
                    TrackFn::MinContent => {
                        t.limit = if t.limit.is_infinite() {
                            c.min
                        } else {
                            t.limit.max(c.min)
                        };
                    }
                    TrackFn::Auto | TrackFn::MaxContent => {
                        t.limit = if t.limit.is_infinite() {
                            c.max
                        } else {
                            t.limit.max(c.max)
                        };
                    }
                    TrackFn::FitContent(l) => {
                        let cap = l.resolve(track_avail).unwrap_or(f32::INFINITY);
                        let v = if t.limit.is_infinite() {
                            c.max
                        } else {
                            t.limit.max(c.max)
                        };
                        t.limit = v.min(cap).max(t.base);
                    }
                    _ => {}
                }
                if t.limit < t.base {
                    t.limit = t.base;
                }
            }
            continue;
        }
        // Spanning items (§11.5 steps 3+, with §11.5.1 distribution).
        distribute_group(tracks, &group, span_gaps, false);
        distribute_group(tracks, &group, span_gaps, true);
    }
    // Flexible-track spanners (§11.5, step 4): distribute the item's minimum
    // contribution to the spanned flexible tracks by flex-factor ratio (all
    // together). Per §11.5.1, growing a track's BASE size to accommodate a
    // spanning item's minimum contribution affects only tracks with an
    // INTRINSIC min track sizing function. So a `minmax(0, 1fr)` track — whose
    // minimum is a fixed `0` — is treated as inflexible here: its base stays
    // 0 and §11.7 sizes it from the (definite) free space, letting the item's
    // own `max-width` shrink it to fit. Bare `1fr` = `minmax(auto, 1fr)` can
    // instead grow to an explicit item minimum. A multi-track flexible span
    // has a zero automatic item minimum (§6.6), not its min-content size.
    let fr_items: Vec<&Contrib> = items
        .iter()
        .filter(|c| crosses_fr(&c.tracks, tracks))
        .collect();
    for phase in 0..3 {
        let growable = |t: &Track| {
            matches!(t.size.max, TrackFn::Fr(_))
                && match phase {
                    0 => t.size.min.is_intrinsic(),
                    1 => matches!(t.size.min, TrackFn::MinContent | TrackFn::MaxContent),
                    _ => matches!(t.size.min, TrackFn::MaxContent),
                }
        };
        for c in &fr_items {
            // Tracks that don't grow here (fixed tracks, and flexible tracks with
            // a fixed minimum) count as fixed at their current base size.
            let others: f32 = tracks[c.tracks.clone()]
                .iter()
                .filter(|t| !growable(t))
                .map(|t| t.base)
                .sum();
            let contribution = match phase {
                0 => c.minimum,
                1 => c.min,
                _ => c.max,
            };
            let space = (contribution - others - span_gaps(&c.tracks, tracks)).max(0.0);
            let factors: f32 = tracks[c.tracks.clone()]
                .iter()
                .filter(|t| growable(t))
                .filter_map(|t| match t.size.max {
                    TrackFn::Fr(f) => Some(f),
                    _ => None,
                })
                .sum();
            let denom = factors.max(1.0);
            for t in tracks[c.tracks.clone()].iter_mut() {
                if growable(t)
                    && let TrackFn::Fr(f) = t.size.max
                {
                    t.base = t.base.max(space * (f / denom));
                }
            }
        }
    }
    // Any remaining infinite growth limit → base size.
    for t in tracks.iter_mut() {
        if t.limit.is_infinite() {
            t.limit = t.base;
        }
    }

    // §11.6 maximize: distribute positive free space equally to bases,
    // freezing at growth limits.
    if track_avail.is_none() && !min_content {
        // An auto-sized axis is sized under a max-content constraint; maximize
        // with infinite free space (§11.6) up to the growth limits. A
        // scrollable item's zero auto minimum must not collapse auto rows.
        for t in tracks.iter_mut() {
            t.base = t.limit;
        }
    }
    if let Some(av) = track_avail {
        let mut free = av - tracks.iter().map(|t| t.base).sum::<f32>();
        if free > 0.0 {
            loop {
                let open: Vec<usize> = (0..tracks.len())
                    .filter(|&i| !tracks[i].collapsed && tracks[i].base < tracks[i].limit)
                    .collect();
                if open.is_empty() || free <= 0.001 {
                    break;
                }
                let share = free / open.len() as f32;
                let mut used = 0.0;
                for &i in &open {
                    let grow = share.min(tracks[i].limit - tracks[i].base);
                    tracks[i].base += grow;
                    used += grow;
                }
                free -= used;
                if used <= 0.0 {
                    break;
                }
            }
        }
    }

    // §11.7 expand flexible tracks.
    let has_fr = tracks.iter().any(|t| matches!(t.size.max, TrackFn::Fr(_)));
    if has_fr && !min_content {
        let fr_size = match track_avail {
            Some(av) => {
                let free = av - tracks.iter().map(|t| t.base).sum::<f32>();
                if free > 0.0 {
                    find_fr_size(tracks, av)
                } else {
                    0.0
                }
            }
            None => {
                // CSS Grid 2 #algo-flex-tracks: with indefinite free space,
                // BOTH track bases and spanning items' max-content sizes
                // determine the flex fraction. A multi-track item's automatic
                // minimum can be zero; using only bases collapses its flexible
                // rows even when they contain visible content.
                let from_bases = tracks
                    .iter()
                    .filter_map(|t| match t.size.max {
                        TrackFn::Fr(f) if f > 1.0 => Some(t.base / f),
                        TrackFn::Fr(_) => Some(t.base),
                        _ => None,
                    })
                    .fold(0.0f32, f32::max);
                fr_items.iter().fold(from_bases, |fraction, item| {
                    fraction.max(find_fr_size(
                        &tracks[item.tracks.clone()],
                        (item.max - span_gaps(&item.tracks, tracks)).max(0.0),
                    ))
                })
            }
        };
        for t in tracks.iter_mut() {
            if t.collapsed {
                continue;
            }
            if let TrackFn::Fr(f) = t.size.max {
                t.base = t.base.max(fr_size * f);
            }
        }
    }

    // §11.8 stretch auto tracks.
    if stretch && let Some(av) = track_avail {
        let free = av - tracks.iter().map(|t| t.base).sum::<f32>();
        if free > 0.0 {
            let autos: Vec<usize> = (0..tracks.len())
                .filter(|&i| !tracks[i].collapsed && matches!(tracks[i].size.max, TrackFn::Auto))
                .collect();
            if !autos.is_empty() {
                let share = free / autos.len() as f32;
                for i in autos {
                    tracks[i].base += share;
                }
            }
        }
    }
}

/// §11.5's spanning-item phases over one span group: `limits == false`
/// distributes contributions into BASE sizes (minimum then max-content
/// minimums), `true` into GROWTH LIMITS (with the infinitely-growable
/// marking). Distribution per §11.5.1: equally up to limits, then beyond
/// limits into intrinsic-max tracks.
fn distribute_group(
    tracks: &mut [Track],
    group: &[&Contrib],
    span_gaps: impl Fn(&Range<usize>, &[Track]) -> f32,
    limits: bool,
) {
    let mut planned: std::collections::HashMap<usize, f32> = std::collections::HashMap::new();
    // §11.5: minimum, min-content, then max-content contributions grow
    // bases. Growth limits only use the two content contributions.
    for phase in if limits { 1..3 } else { 0..3 } {
        planned.clear();
        for c in group {
            let contribution = match phase {
                0 => c.minimum,
                1 => c.min,
                _ => c.max,
            };
            let affected: Vec<usize> = c
                .tracks
                .clone()
                .filter(|&i| {
                    if tracks[i].collapsed {
                        return false;
                    }
                    if limits {
                        tracks[i].size.max.is_intrinsic()
                            && (phase == 1 || !matches!(tracks[i].size.max, TrackFn::MinContent))
                    } else if phase == 2 {
                        // The max-content pass only affects max-content mins.
                        matches!(tracks[i].size.min, TrackFn::MaxContent)
                    } else if phase == 1 {
                        matches!(
                            tracks[i].size.min,
                            TrackFn::MinContent | TrackFn::MaxContent
                        )
                    } else {
                        tracks[i].size.min.is_intrinsic()
                    }
                })
                .collect();
            if affected.is_empty() {
                continue;
            }
            let spanned_sum: f32 = c
                .tracks
                .clone()
                .map(|i| {
                    if limits {
                        if tracks[i].limit.is_infinite() {
                            tracks[i].base
                        } else {
                            tracks[i].limit
                        }
                    } else {
                        tracks[i].base
                    }
                })
                .sum();
            let mut space = contribution - spanned_sum - span_gaps(&c.tracks, tracks);
            if space <= 0.0 {
                continue;
            }
            // Equal distribution up to limits, then beyond into
            // intrinsic-max tracks (§11.5.1 steps 2 + 4).
            let mut inc: std::collections::HashMap<usize, f32> = std::collections::HashMap::new();
            let mut open: Vec<usize> = affected.clone();
            while space > 0.001 && !open.is_empty() {
                let share = space / open.len() as f32;
                let mut used = 0.0;
                let mut next: Vec<usize> = Vec::new();
                for &i in &open {
                    let cur = tracks[i].base + inc.get(&i).copied().unwrap_or(0.0);
                    let cap = if limits {
                        if tracks[i].limit.is_infinite() || tracks[i].inf_growable {
                            f32::INFINITY
                        } else {
                            tracks[i].limit
                        }
                    } else {
                        tracks[i].limit
                    };
                    let room = (cap - cur).max(0.0);
                    let grow = share.min(room);
                    *inc.entry(i).or_default() += grow;
                    used += grow;
                    if grow >= share - 0.0001 {
                        next.push(i);
                    }
                }
                space -= used;
                open = next;
                if used <= 0.0 {
                    break;
                }
            }
            // Beyond limits: intrinsic-max tracks (else all affected).
            if space > 0.001 {
                let beyond: Vec<usize> = affected
                    .iter()
                    .copied()
                    .filter(|&i| tracks[i].size.max.is_intrinsic())
                    .collect();
                let set = if beyond.is_empty() {
                    &affected
                } else {
                    &beyond
                };
                let share = space / set.len() as f32;
                for &i in set {
                    *inc.entry(i).or_default() += share;
                }
            }
            for (i, v) in inc {
                let p = planned.entry(i).or_default();
                *p = p.max(v);
            }
        }
        // Commit the group's planned increases.
        for (&i, &v) in &planned {
            if v <= 0.0 {
                continue;
            }
            if limits {
                if tracks[i].limit.is_infinite() {
                    tracks[i].limit = tracks[i].base + v;
                    tracks[i].inf_growable = true;
                } else {
                    tracks[i].limit += v;
                }
            } else {
                tracks[i].base += v;
                if tracks[i].limit < tracks[i].base {
                    tracks[i].limit = tracks[i].base;
                }
            }
        }
    }
}

/// §11.7.1 find-the-size-of-an-fr: the largest fr size that fills `space`
/// exactly, iteratively treating too-small flexible tracks as inflexible.
fn find_fr_size(tracks: &[Track], space: f32) -> f32 {
    // Collapsed (auto-fit) tracks are never flexible: they would siphon
    // fr space into zero-width tracks otherwise.
    let mut inflexible: Vec<bool> = tracks
        .iter()
        .map(|t| t.collapsed || !matches!(t.size.max, TrackFn::Fr(_)))
        .collect();
    loop {
        let leftover: f32 = space
            - tracks
                .iter()
                .zip(&inflexible)
                .map(|(t, &inf)| if inf { t.base } else { 0.0 })
                .sum::<f32>();
        let factor_sum: f32 = tracks
            .iter()
            .zip(&inflexible)
            .filter(|(_, inf)| !**inf)
            .map(|(t, _)| match t.size.max {
                TrackFn::Fr(f) => f,
                _ => 0.0,
            })
            .sum();
        if factor_sum <= 0.0 {
            return 0.0;
        }
        let hyp = leftover / factor_sum.max(1.0);
        let mut restarted = false;
        for (i, t) in tracks.iter().enumerate() {
            if inflexible[i] {
                continue;
            }
            if let TrackFn::Fr(f) = t.size.max
                && hyp * f < t.base
            {
                inflexible[i] = true;
                restarted = true;
            }
        }
        if !restarted {
            return hyp.max(0.0);
        }
    }
}

/// Map a content-distribution keyword onto the shared distribution model.
fn dist_of(v: Option<&str>) -> Justify {
    match v.unwrap_or("").trim().to_ascii_lowercase().as_str() {
        "end" | "flex-end" | "right" => Justify::End,
        "center" => Justify::Center,
        "space-between" => Justify::Between,
        "space-around" => Justify::Around,
        "space-evenly" => Justify::Evenly,
        _ => Justify::Start,
    }
}

/// Whether a content-distribution keyword stretches auto tracks (§11.8:
/// `normal` or `stretch`).
fn dist_stretches(v: Option<&str>) -> bool {
    matches!(
        v.unwrap_or("normal").trim().to_ascii_lowercase().as_str(),
        "normal" | "stretch" | ""
    )
}

/// A self-alignment keyword (justify-self/align-self and their *-items
/// defaults) mapped to the shared AlignItem model. `auto`/absent falls back
/// to the container's *-items value; `normal` behaves as stretch for
/// non-replaced grid items (css-align §6.1.2).
fn self_align(own: Option<&str>, items_default: super::flex::AlignItem) -> super::flex::AlignItem {
    use super::flex::AlignItem;
    match own.unwrap_or("").trim().to_ascii_lowercase().as_str() {
        "start" | "flex-start" | "self-start" | "left" => AlignItem::Start,
        "end" | "flex-end" | "self-end" | "right" => AlignItem::End,
        "center" => AlignItem::Center,
        "stretch" | "normal" => AlignItem::Stretch,
        "baseline" | "first baseline" | "last baseline" => AlignItem::Baseline,
        _ => items_default,
    }
}

impl Flow<'_> {
    /// CSS Grid 2 §6.6 / §12.5: auto tracks use the item's *minimum*
    /// contribution, not necessarily its min-content contribution. The
    /// latter remains available for explicit min-/max-content track functions.
    #[allow(clippy::too_many_arguments)]
    fn grid_minimum_contribution(
        &self,
        item: &BoxNode,
        spanned: &[Track],
        column: bool,
        min_content: f32,
        max_content: f32,
        bp: f32,
        margins: f32,
    ) -> f32 {
        let s = &item.style;
        let (preferred, minimum) = if column {
            (&s.width, &s.min_width)
        } else {
            (&s.height, &s.min_height)
        };
        // A definite preferred size contributes even on a scroll container.
        // Percentages are cyclic while determining the grid area's size.
        if preferred.resolve(None).is_some()
            || matches!(
                preferred,
                Len::MinContent | Len::MaxContent | Len::FitContent | Len::FitContentLimit(_)
            )
        {
            return min_content;
        }
        match minimum {
            Len::Auto => {
                let content_based = !self.scroll_container(item.node)
                    && spanned.iter().any(|t| matches!(t.size.min, TrackFn::Auto))
                    && !(spanned.len() > 1
                        && spanned.iter().any(|t| matches!(t.size.max, TrackFn::Fr(_))));
                if content_based {
                    min_content
                } else {
                    bp + margins
                }
            }
            Len::MinContent => min_content,
            Len::MaxContent => max_content,
            Len::FitContent | Len::FitContentLimit(_) => min_content,
            length => {
                let size = length.resolve(Some(0.0)).unwrap_or(0.0).max(0.0);
                if s.border_box {
                    size.max(bp) + margins
                } else {
                    size + bp + margins
                }
            }
        }
    }

    /// Placement and column sizing are shared by intrinsic queries and
    /// final layout (CSS Grid 2 #intrinsic-sizes / #algo-track-sizing).
    #[allow(clippy::too_many_arguments)]
    fn grid_setup<'t>(
        &self,
        b: &BoxNode,
        items: &'t [SharedBox],
        basis: Option<f32>,
        def_ch: Option<f32>,
        inl: &InlineStyle,
        mode: Option<IMode>,
    ) -> GridSetup<'t> {
        let node = b.node;
        let u = Units::of(self.dom, node);
        let cv = |p: &str| self.dom.computed_value_resolved(node, p);
        let inherited = self.subgrid_rows.borrow().inputs.get(&node).cloned();

        // Gaps: `gap` = <row-gap> <column-gap>; longhands win.
        let (short_row, short_col) = {
            let g = cv("gap").unwrap_or_default();
            let mut parts = g.split_whitespace();
            let a = parts.next().map(str::to_string);
            let bb = parts.next().map(str::to_string).or_else(|| a.clone());
            (a, bb)
        };
        let parse_gap = |long: Option<String>, short: Option<String>, basis: Option<f32>| {
            long.or(short)
                .and_then(|v| Len::parse(&v, u, self.vp))
                .and_then(|l| l.resolve(basis))
                .unwrap_or(0.0)
                .max(0.0)
        };
        let gap_col = parse_gap(cv("column-gap"), short_col, basis);
        let row_gap_value = cv("row-gap").or(short_row);
        let gap_row = if row_gap_value
            .as_deref()
            .is_none_or(|v| v.trim().is_empty() || v.trim() == "normal")
        {
            inherited.as_ref().map_or(0.0, |r| r.gap)
        } else {
            parse_gap(row_gap_value, None, def_ch)
        };

        // Named areas + explicit templates.
        let areas = cv("grid-template-areas").as_deref().and_then(parse_areas);
        let (area_rows_n, area_cols_n) = areas.as_ref().map_or((0, 0), |(_, r, c)| (*r, *c));
        let auto_ts = || TrackSize {
            min: TrackFn::Auto,
            max: TrackFn::Auto,
        };
        let mut cols: Vec<Track> = cv("grid-template-columns")
            .as_deref()
            .and_then(|v| parse_template(v, u, self.vp, basis, gap_col))
            .unwrap_or_default();
        let mut rows: Vec<Track> =
            inherited
                .as_ref()
                .map(|r| r.tracks.clone())
                .unwrap_or_else(|| {
                    cv("grid-template-rows")
                        .as_deref()
                        .and_then(|v| parse_template(v, u, self.vp, def_ch, gap_row))
                        .unwrap_or_default()
                });
        while cols.len() < area_cols_n {
            cols.push(Track::new(auto_ts(), false));
        }
        while inherited.is_none() && rows.len() < area_rows_n {
            rows.push(Track::new(auto_ts(), false));
        }
        let explicit_cols = cols.len();
        let explicit_rows = rows.len();

        let flow_v = cv("grid-auto-flow")
            .unwrap_or_default()
            .to_ascii_lowercase();
        let row_flow = !flow_v.contains("column");
        let dense = flow_v.contains("dense");

        // §8.5 note: order-modified document order.
        let mut idx: Vec<usize> = (0..items.len()).collect();
        idx.sort_by_key(|&i| self.order_of(items[i].node));
        let ordered: Vec<&'t BoxNode> = idx.iter().map(|&i| items[i].as_ref()).collect();

        // Per-item grid lines: grid-area, overridden by grid-row/column
        // shorthands, overridden by the *-start/*-end longhands.
        let mut col_names = template_line_names(
            &cv("grid-template-columns").unwrap_or_default(),
            explicit_cols,
        );
        let mut row_names = if let Some(parent) = &inherited {
            let mut names = parent.names.clone();
            let serialized = serialize_subgrid_rows(
                &cv("grid-template-rows").unwrap_or_default(),
                explicit_rows,
            );
            for (line, token) in named_track_tokens(&serialized)
                .into_iter()
                .skip(1)
                .enumerate()
            {
                if let Some(group) = token.strip_prefix('[').and_then(|v| v.strip_suffix(']')) {
                    names[line].extend(group.split_whitespace().map(str::to_owned));
                }
            }
            names
        } else {
            template_line_names(&cv("grid-template-rows").unwrap_or_default(), explicit_rows)
        };
        if let Some((areas, _, _)) = &areas {
            for (name, (rr, cc)) in areas {
                for (names, range) in [(&mut col_names, cc), (&mut row_names, rr)] {
                    if let Some(line) = names.get_mut(range.start) {
                        line.push(format!("{name}-start"));
                    }
                    if let Some(line) = names.get_mut(range.end) {
                        line.push(format!("{name}-end"));
                    }
                }
            }
        }
        let mut placements: Vec<(AxisPlace, AxisPlace)> = ordered
            .iter()
            .map(|it| {
                let icv = |p: &str| {
                    if it.node == NO_NODE {
                        None
                    } else {
                        self.dom.computed_value_resolved(it.node, p)
                    }
                };
                // grid-area: row-start / col-start / row-end / col-end with
                // the §8.4 backfill (a lone ident names the whole area).
                let ga = icv("grid-area").unwrap_or_default();
                let parts: Vec<&str> = if ga.trim().is_empty() {
                    Vec::new()
                } else {
                    ga.split('/').map(str::trim).collect()
                };
                let part = |i: usize| parts.get(i).copied();
                let backfill = |i: usize, from: Option<&str>| -> LineRaw {
                    match part(i) {
                        Some(v) => parse_grid_line(Some(v)),
                        None => match from {
                            Some(v) if matches!(parse_grid_line(Some(v)), LineRaw::Name(_)) => {
                                parse_grid_line(Some(v))
                            }
                            _ => LineRaw::Auto,
                        },
                    }
                };
                let mut rs = backfill(0, None);
                let mut cs = backfill(1, part(0));
                let mut re = backfill(2, part(0));
                let mut ce = backfill(3, part(1).or(part(0)));
                if let Some(v) = icv("grid-row") {
                    let (a, b2) = v
                        .split_once('/')
                        .map_or((v.as_str(), None), |(a, b2)| (a, Some(b2)));
                    rs = parse_grid_line(Some(a));
                    re = parse_grid_line(b2);
                }
                if let Some(v) = icv("grid-column") {
                    let (a, b2) = v
                        .split_once('/')
                        .map_or((v.as_str(), None), |(a, b2)| (a, Some(b2)));
                    cs = parse_grid_line(Some(a));
                    ce = parse_grid_line(b2);
                }
                if let Some(v) = icv("grid-row-start") {
                    rs = parse_grid_line(Some(&v));
                }
                if let Some(v) = icv("grid-row-end") {
                    re = parse_grid_line(Some(&v));
                }
                if let Some(v) = icv("grid-column-start") {
                    cs = parse_grid_line(Some(&v));
                }
                if let Some(v) = icv("grid-column-end") {
                    ce = parse_grid_line(Some(&v));
                }
                (
                    resolve_axis(cs, ce, explicit_cols, &col_names),
                    resolve_axis(rs, re, explicit_rows, &row_names),
                )
            })
            .collect();
        // Grid 2 #implicit-grids: signed placements can create tracks on
        // either side. Shift all definite placements by the prepended extent
        // before passing nonnegative indices to the occupancy algorithm.
        let before_cols = placements
            .iter()
            .filter_map(|(c, _)| c.start)
            .min()
            .unwrap_or(0)
            .min(0)
            .unsigned_abs() as usize;
        let before_rows = if inherited.is_some() {
            0
        } else {
            placements
                .iter()
                .filter_map(|(_, r)| r.start)
                .min()
                .unwrap_or(0)
                .min(0)
                .unsigned_abs() as usize
        };
        for (c, r) in &mut placements {
            c.start = c.start.map(|n| n + before_cols as i32);
            r.start = r.start.map(|n| (n + before_rows as i32).max(0));
        }
        // §8.5 works in flow-relative axes: its "columns" are the real
        // columns under row flow, the real ROWS under column flow.
        let minor_tracks = if row_flow {
            explicit_cols + before_cols
        } else {
            explicit_rows + before_rows
        };
        let mut placed = auto_place(placements, minor_tracks.max(1), row_flow, dense);
        if inherited.is_some() {
            // #subgrid-implicit: placement is resolved normally, then clamped
            // to the inherited explicit grid. No implicit subgrid rows exist.
            for p in &mut placed {
                p.rows.start = p.rows.start.min(explicit_rows - 1);
                p.rows.end = p.rows.end.min(explicit_rows).max(p.rows.start + 1);
            }
        }

        // Implicit tracks from grid-auto-columns/rows (a list cycles).
        let auto_list = |prop: &str| -> Vec<TrackSize> {
            let list: Vec<TrackSize> = cv(prop)
                .as_deref()
                .map(|v| {
                    split_track_tokens(v)
                        .iter()
                        .filter_map(|t| parse_track_size(t, u, self.vp))
                        .collect()
                })
                .unwrap_or_default();
            if list.is_empty() {
                vec![auto_ts()]
            } else {
                list
            }
        };
        let auto_cols = auto_list("grid-auto-columns");
        let auto_rows = auto_list("grid-auto-rows");
        // Auto-track patterns count backwards before the explicit grid.
        for (tracks, pattern, count) in [
            (&mut cols, &auto_cols, before_cols),
            (&mut rows, &auto_rows, before_rows),
        ] {
            let prefix = (0..count)
                .map(|i| {
                    let index = (pattern.len() - (count - i) % pattern.len()) % pattern.len();
                    Track::new(pattern[index].clone(), false)
                })
                .collect::<Vec<_>>();
            tracks.splice(0..0, prefix);
        }
        let need_cols = placed.iter().map(|p| p.cols.end).max().unwrap_or(0);
        let need_rows = placed.iter().map(|p| p.rows.end).max().unwrap_or(0);
        while cols.len() < need_cols {
            let i = (cols.len() - explicit_cols - before_cols) % auto_cols.len();
            cols.push(Track::new(auto_cols[i].clone(), false));
        }
        while rows.len() < need_rows {
            let i = (rows.len() - explicit_rows - before_rows) % auto_rows.len();
            rows.push(Track::new(auto_rows[i].clone(), false));
        }
        row_names.splice(0..0, (0..before_rows).map(|_| Vec::new()));
        row_names.resize(rows.len() + 1, Vec::new());

        // auto-fit: collapse repetition tracks no item spans (§7.2.3.2).
        for (ci, t) in cols.iter_mut().enumerate() {
            if t.collapsible && !placed.iter().any(|p| p.cols.contains(&ci)) {
                t.collapsed = true;
            }
        }
        for (ri, t) in rows.iter_mut().enumerate() {
            if t.collapsible && !placed.iter().any(|p| p.rows.contains(&ri)) {
                t.collapsed = true;
            }
        }

        // ---- §11 column sizing from intrinsic contributions ----
        let mut col_contribs: Vec<Contrib> = ordered
            .iter()
            .zip(&placed)
            .map(|(it, p)| {
                let min = self.contribution(it, IMode::Min, inl);
                let max = self.contribution(it, IMode::Max, inl);
                let s = &it.style;
                let bp = s.border[LEFT]
                    + s.border[RIGHT]
                    + self.pad(s, LEFT, 0.0)
                    + self.pad(s, RIGHT, 0.0);
                let margins = s.margin[LEFT].resolve(Some(0.0)).unwrap_or(0.0)
                    + s.margin[RIGHT].resolve(Some(0.0)).unwrap_or(0.0);
                Contrib {
                    tracks: p.cols.clone(),
                    minimum: self.grid_minimum_contribution(
                        it,
                        &cols[p.cols.clone()],
                        true,
                        min,
                        max,
                        bp,
                        margins,
                    ),
                    min,
                    max,
                }
            })
            .collect();
        if mode.is_some() {
            for contribution in &mut col_contribs {
                let limits = cols[contribution.tracks.clone()]
                    .iter()
                    .map(|t| match &t.size.max {
                        TrackFn::FitContent(v) => v.resolve(None),
                        other => other.definite(None),
                    })
                    .collect::<Option<Vec<_>>>();
                let limited = limits.map_or(contribution.min, |v| {
                    contribution.min.min(
                        v.iter().sum::<f32>()
                            + gap_col * contribution.tracks.len().saturating_sub(1) as f32,
                    )
                });
                contribution.minimum = contribution.minimum.max(limited);
            }
        }
        let jc = cv("justify-content");
        size_tracks_constrained(
            &mut cols,
            &col_contribs,
            basis,
            gap_col,
            dist_stretches(jc.as_deref()),
            mode == Some(IMode::Min),
        );
        GridSetup {
            ordered,
            cols,
            rows,
            placed,
            row_names,
            gap_col,
            gap_row,
            inherited,
        }
    }

    pub(super) fn grid_intrinsic_width(
        &self,
        b: &BoxNode,
        items: &[SharedBox],
        mode: IMode,
        inl: &InlineStyle,
    ) -> f32 {
        let setup = self.grid_setup(b, items, None, None, inl, Some(mode));
        let live = setup.cols.iter().filter(|t| !t.collapsed).count();
        setup.cols.iter().map(|t| t.base).sum::<f32>()
            + setup.gap_col * live.saturating_sub(1) as f32
    }

    /// Lay a grid container's items (css-grid-1): placement → column
    /// sizing (§11) → item layout at real track widths → row sizing (§11 in
    /// the block axis, contributions = laid heights) → §10.4/§10.5 track
    /// alignment and §6.6-adjacent item alignment.
    #[allow(clippy::too_many_arguments)]
    pub(super) fn grid_content<'t>(
        &self,
        b: &'t BoxNode,
        items: &'t [SharedBox],
        content_x: f32,
        content_top: f32,
        content_w: f32,
        def_ch: Option<f32>,
        inl: &InlineStyle,
        anchors: &mut Vec<(NodeId, f32)>,
    ) -> (Vec<Frag<'t>>, f32) {
        use super::flex::AlignItem;
        let node = b.node;
        let cv = |p: &str| self.dom.computed_value_resolved(node, p);
        let jc = cv("justify-content");
        let GridSetup {
            ordered,
            cols,
            mut rows,
            placed,
            row_names,
            gap_col,
            gap_row,
            inherited,
        } = self.grid_setup(b, items, Some(content_w), def_ch, inl, None);

        // Track positions + content-distribution of leftover main space.
        let positions =
            |tracks: &[Track], gap: f32, avail: Option<f32>, dist: Justify| -> Vec<f32> {
                let live = tracks.iter().filter(|t| !t.collapsed).count();
                let total: f32 = tracks.iter().map(|t| t.base).sum::<f32>()
                    + gap * live.saturating_sub(1) as f32;
                let free = avail.map_or(0.0, |a| a - total);
                let (lead, between) = justify_offsets(dist, free, live);
                let mut xs = Vec::with_capacity(tracks.len());
                let mut x = lead.max(0.0);
                let mut seen_live = 0usize;
                for t in tracks {
                    if t.collapsed {
                        xs.push(x);
                        continue;
                    }
                    if seen_live > 0 {
                        x += gap + between;
                    }
                    xs.push(x);
                    x += t.base;
                    seen_live += 1;
                }
                xs
            };
        let col_x = positions(&cols, gap_col, Some(content_w), dist_of(jc.as_deref()));

        // ---- lay items at their area widths ----
        // (`place-items`/`place-self` expand to these longhands in the
        // cascade, so only the longhands are read here.)
        let justify_items = self_align(cv("justify-items").as_deref(), AlignItem::Stretch);
        let align_items = self_align(cv("align-items").as_deref(), AlignItem::Stretch);
        struct GItem<'t> {
            it: &'t BoxNode,
            frag: Frag<'t>,
            anchors: Vec<(NodeId, f32)>,
            m: [f32; 4],
            auto: [bool; 4],
            align: AlignItem,
            last_baseline: bool,
            baseline_shim: f32,
            border_x: f32,
            content_w: f32,
            bp_cross: f32,
            /// The item's grid-area width (its containing block — css-grid
            /// §9.1; the §9.4.3 relative-offset percentage basis).
            area_w: f32,
            /// The item's cross (height) property is auto — stretch applies.
            cross_auto: bool,
            subgrid: Option<RowInput>,
            row_contributions: Option<Vec<Contrib>>,
        }
        let mut gitems: Vec<GItem<'t>> = Vec::with_capacity(ordered.len());
        for (it, p) in ordered.iter().zip(&placed) {
            let s = &it.style;
            let (m, auto) = self.margins_of(s, content_w);
            let area_x = col_x[p.cols.start];
            let last = p.cols.end - 1;
            let area_w = (col_x[last] + cols[last].base - area_x).max(0.0);
            let bp_l = s.border[LEFT] + self.pad(s, LEFT, area_w);
            let bp_r = s.border[RIGHT] + self.pad(s, RIGHT, area_w);
            let bp_h = bp_l + bp_r;
            let bp_cross = s.border[TOP]
                + s.border[BOTTOM]
                + self.pad(s, TOP, area_w)
                + self.pad(s, BOTTOM, area_w);
            let to_content = |v: f32| {
                if s.border_box {
                    (v - bp_h).max(0.0)
                } else {
                    v.max(0.0)
                }
            };
            let icv = |pn: &str| {
                if it.node == NO_NODE {
                    None
                } else {
                    self.dom.computed_value_resolved(it.node, pn)
                }
            };
            let justify = self_align(icv("justify-self").as_deref(), justify_items);
            let width_value = |l: &Len| {
                self.intrinsic_width_value(l, it, Some(area_w), inl)
                    .or_else(|| l.resolve(Some(area_w)).map(to_content))
            };
            let width_def = width_value(&s.width);
            let avail_c = (area_w - m[LEFT] - m[RIGHT] - bp_h).max(0.0);
            let w = match width_def {
                Some(v) => v,
                None if justify == AlignItem::Stretch && !auto[LEFT] && !auto[RIGHT] => avail_c,
                None => {
                    let minc = self.intrinsic_w(it, IMode::Min, inl);
                    let maxc = self.intrinsic_w(it, IMode::Max, inl).max(minc);
                    avail_c.max(minc).min(maxc)
                }
            };
            let min = width_value(&s.min_width).unwrap_or(0.);
            let max = width_value(&s.max_width).unwrap_or(f32::INFINITY).max(min);
            let w = w.clamp(min, max);
            let subgrid = (matches!(it.content, Content::Grid(_))
                && self.dom.is_row_subgrid_item(it.node))
            .then(|| RowInput {
                tracks: rows[p.rows.clone()].to_vec(),
                names: row_names[p.rows.start..=p.rows.end].to_vec(),
                positions: None,
                gap: gap_row,
                start_edge: m[TOP] + s.border[TOP] + self.pad(s, TOP, area_w),
                end_edge: m[BOTTOM] + s.border[BOTTOM] + self.pad(s, BOTTOM, area_w),
            });
            if let Some(input) = &subgrid {
                self.subgrid_rows
                    .borrow_mut()
                    .inputs
                    .insert(it.node, input.clone());
            }
            let def_h = if subgrid.is_some() {
                None
            } else {
                s.height.resolve(def_ch).map(|v| v.max(0.0))
            };
            let (frag, anc) = self.item_frag(it, w.max(0.0), area_w, def_h, inl);
            let row_contributions = if subgrid.is_some() {
                let mut state = self.subgrid_rows.borrow_mut();
                state.inputs.remove(&it.node);
                state.contributions.remove(&it.node)
            } else {
                None
            };
            // Horizontal placement within the area (css-align self-alignment;
            // auto margins win over the alignment keyword).
            let extra = area_w - (frag.w + m[LEFT] + m[RIGHT]);
            let shift = super::flow::cross_shift(extra, auto[LEFT], auto[RIGHT], justify);
            let last_baseline = icv("align-self")
                .filter(|v| v != "auto")
                .or_else(|| cv("align-items"))
                .as_deref()
                == Some("last baseline");
            let mut alignment = self_align(icv("align-self").as_deref(), align_items);
            let cyclic_height = [&s.height, &s.min_height, &s.max_height]
                .iter()
                .any(|v| matches!(v,Len::Val(n) if n.resolve(None).is_none()));
            if alignment == AlignItem::Baseline
                && cyclic_height
                && rows[p.rows.clone()].iter().any(|t| {
                    !matches!(t.size.min, TrackFn::Fixed(_))
                        || !matches!(t.size.max, TrackFn::Fixed(_))
                })
            {
                alignment = if last_baseline {
                    AlignItem::End
                } else {
                    AlignItem::Start
                };
            }
            gitems.push(GItem {
                it,
                border_x: area_x + shift + m[LEFT],
                content_w: w.max(0.0),
                bp_cross,
                cross_auto: subgrid.is_some() || matches!(s.height, Len::Auto),
                area_w,
                frag,
                anchors: anc,
                m,
                auto,
                align: if subgrid.is_some() {
                    AlignItem::Stretch
                } else {
                    alignment
                },
                last_baseline,
                baseline_shim: 0.,
                subgrid,
                row_contributions,
            });
        }

        // CSS Grid 2 #algo-baseline-shims / CSS Align 3 #align-by-baseline:
        // each row's first/last baseline-sharing groups contribute the shim
        // needed to align their baselines before intrinsic track sizing.
        let mut baseline_groups: std::collections::HashMap<(usize, bool), f32> =
            std::collections::HashMap::new();
        for (g, p) in gitems.iter().zip(&placed) {
            if g.align != AlignItem::Baseline || g.auto[TOP] || g.auto[BOTTOM] {
                continue;
            }
            let baseline = if g.last_baseline {
                super::flow::last_baseline(&g.frag)
            } else {
                super::flow::first_baseline(&g.frag)
            }
            .unwrap_or(g.frag.h);
            let edge = if g.last_baseline {
                g.m[BOTTOM] + g.frag.h - baseline
            } else {
                g.m[TOP] + baseline
            };
            let line = if g.last_baseline {
                p.rows.end - 1
            } else {
                p.rows.start
            };
            baseline_groups
                .entry((line, g.last_baseline))
                .and_modify(|old| *old = old.max(edge))
                .or_insert(edge);
        }
        for (g, p) in gitems.iter_mut().zip(&placed) {
            if g.align != AlignItem::Baseline || g.auto[TOP] || g.auto[BOTTOM] {
                continue;
            }
            let baseline = if g.last_baseline {
                super::flow::last_baseline(&g.frag)
            } else {
                super::flow::first_baseline(&g.frag)
            }
            .unwrap_or(g.frag.h);
            let edge = if g.last_baseline {
                g.m[BOTTOM] + g.frag.h - baseline
            } else {
                g.m[TOP] + baseline
            };
            let line = if g.last_baseline {
                p.rows.end - 1
            } else {
                p.rows.start
            };
            g.baseline_shim = (baseline_groups[&(line, g.last_baseline)] - edge).max(0.);
        }

        // ---- §11 row sizing from laid heights ----
        let row_contribs: Vec<Contrib> = gitems
            .iter()
            .zip(&placed)
            .flat_map(|(g, p)| {
                if let Some(contributions) = &g.row_contributions {
                    return contributions
                        .iter()
                        .map(|c| Contrib {
                            tracks: c.tracks.start + p.rows.start..c.tracks.end + p.rows.start,
                            minimum: c.minimum,
                            min: c.min,
                            max: c.max,
                        })
                        .collect::<Vec<_>>();
                }
                let h = g.frag.h + g.m[TOP] + g.m[BOTTOM] + g.baseline_shim;
                vec![Contrib {
                    tracks: p.rows.clone(),
                    minimum: self.grid_minimum_contribution(
                        g.it,
                        &rows[p.rows.clone()],
                        false,
                        h,
                        h,
                        g.bp_cross,
                        g.m[TOP] + g.m[BOTTOM],
                    ),
                    min: h,
                    max: h,
                }]
            })
            .collect();
        let ac = cv("align-content");
        if let Some(input) = &inherited {
            self.subgrid_rows
                .borrow_mut()
                .contributions
                .insert(node, input.export(row_contribs.clone(), gap_row));
        }
        let row_y = if let Some((inherited_tracks, positions)) =
            inherited.as_ref().and_then(|r| r.resolved(gap_row))
        {
            rows = inherited_tracks;
            positions
        } else {
            size_tracks(
                &mut rows,
                &row_contribs,
                def_ch,
                gap_row,
                dist_stretches(ac.as_deref()),
            );
            positions(
                &rows,
                gap_row,
                def_ch,
                if inherited.is_some() {
                    Justify::Start
                } else {
                    dist_of(ac.as_deref())
                },
            )
        };

        // Record the USED track sizes for the CSSOM resolved value that
        // `getComputedStyle(grid-template-columns/-rows)` reports (§ CSS Grid
        // serialization): the used lengths, not the declared `repeat(…)`.
        if node != NO_NODE {
            self.grid_tracks.borrow_mut().insert(
                node,
                (
                    cols.iter().map(|t| t.base).collect(),
                    rows.iter().map(|t| t.base).collect(),
                ),
            );
        }

        // ---- finalize: vertical alignment within row areas, translate ----
        let mut frags: Vec<Frag<'t>> = Vec::with_capacity(gitems.len());
        for (g, p) in gitems.iter_mut().zip(&placed) {
            let area_y = row_y[p.rows.start];
            let last = p.rows.end - 1;
            let area_h = (row_y[last] + rows[last].base - area_y).max(0.0);
            if g.subgrid.is_some()
                || (g.align == AlignItem::Stretch
                    && g.cross_auto
                    && !g.auto[TOP]
                    && !g.auto[BOTTOM])
            {
                // CSS Grid §11.6/Box Alignment §6.2: stretch changes the
                // grid item's used size. Relayout with that now-definite
                // content-box height so percentage-height descendants see
                // the stretched containing block; patching only `frag.h`
                // leaves their backgrounds and hit regions at the old
                // intrinsic height.
                let stretched = (area_h - g.m[TOP] - g.m[BOTTOM] - g.bp_cross).max(0.0);
                if let Some(input) = &g.subgrid {
                    let mut input = input.clone();
                    input.tracks = rows[p.rows.clone()].to_vec();
                    input.positions =
                        Some(row_y[p.rows.clone()].iter().map(|y| y - area_y).collect());
                    // Content distribution can enlarge the parent's effective
                    // gutters. Normal subgrid gutters follow these used gaps.
                    if p.rows.len() > 1 {
                        input.gap =
                            row_y[p.rows.start + 1] - row_y[p.rows.start] - rows[p.rows.start].base;
                    }
                    self.subgrid_rows
                        .borrow_mut()
                        .inputs
                        .insert(g.it.node, input);
                }
                let (frag, anchors) =
                    self.item_frag(g.it, g.content_w, g.area_w, Some(stretched), inl);
                if g.subgrid.is_some() {
                    let mut state = self.subgrid_rows.borrow_mut();
                    state.inputs.remove(&g.it.node);
                    state.contributions.remove(&g.it.node);
                }
                g.frag = frag;
                g.anchors = anchors;
            }
            let extra = area_h - (g.frag.h + g.m[TOP] + g.m[BOTTOM]);
            let shift = if g.align == AlignItem::Baseline && !g.auto[TOP] && !g.auto[BOTTOM] {
                if g.last_baseline {
                    extra - g.baseline_shim
                } else {
                    g.baseline_shim
                }
            } else {
                super::flow::cross_shift(extra, g.auto[TOP], g.auto[BOTTOM], g.align)
            };
            // §9.4.3 relative offset + transform translation — a grid item's
            // containing block is its grid area (css-grid §9.1).
            let (rx, ry) =
                self.paint_offset(&g.it.style, g.area_w, Some(area_h), g.frag.w, g.frag.h);
            let dx = content_x + g.border_x + rx;
            let dy = content_top + area_y + shift + g.m[TOP] + ry;
            let mut frag = std::mem::replace(&mut g.frag, Frag::empty());
            Flow::offset_frag(&mut frag, dx, dy);
            for &(n, y) in &g.anchors {
                anchors.push((n, y + dy));
            }
            frags.push(frag);
        }
        let live_rows = rows.iter().filter(|t| !t.collapsed).count();
        let content_h = if inherited.as_ref().is_some_and(|r| r.positions.is_some()) {
            row_y
                .last()
                .zip(rows.last())
                .map_or(0.0, |(y, t)| y + t.base)
        } else {
            rows.iter().map(|t| t.base).sum::<f32>() + gap_row * live_rows.saturating_sub(1) as f32
        };
        (frags, content_h.max(0.0))
    }
}

