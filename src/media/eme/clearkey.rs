//! The Clear Key CDM (EME #clear-key): license requests list the key IDs
//! of the initialization data (#clear-key-request-format), licenses are
//! JWK Sets of AES-128 keys (#clear-key-license-format). Sessions are
//! "temporary" only: Clear Key may, but TRust does not, persist licenses.

use std::collections::HashMap;

use super::{KeyRing, base64url_decode, base64url_encode};

/// EME's Common SystemID (format-registry initdata/cenc).
const COMMON_SYSTEM_ID: [u8; 16] = [
    0x10, 0x77, 0xef, 0xec, 0xc0, 0xb2, 0x4d, 0x02, 0xac, 0xe3, 0x3c, 0x1e, 0x52, 0xe2, 0xfb, 0x4b,
];
/// Key IDs per request and keys per license, bounding what a page can make
/// the CDM hold.
const MAX_KEY_IDS: usize = 256;
const MAX_KEY_ID_LEN: usize = 512;

/// How an operation failed, by the exception it rejects with.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Error {
    /// TypeError: the data is invalid for its format.
    Type(String),
    /// NotSupportedError.
    NotSupported(String),
    /// InvalidStateError.
    InvalidState,
}

struct Session {
    /// The key IDs known to the session (with usable keys).
    known: Vec<Vec<u8>>,
}

/// One MediaKeys object's CDM instance.
#[derive(Default)]
pub struct ClearKey {
    ring: KeyRing,
    sessions: HashMap<u32, Session>,
    next_session: u32,
}

impl ClearKey {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn ring(&self) -> KeyRing {
        self.ring.clone()
    }

    pub fn supports_init_data_type(init_data_type: &str) -> bool {
        matches!(init_data_type, "cenc" | "keyids" | "webm")
    }

    /// #dom-mediakeysession-generaterequest's CDM steps: the session id and
    /// the license request message.
    pub fn generate_request(
        &mut self,
        init_data_type: &str,
        init_data: &[u8],
    ) -> Result<(u32, Vec<u8>), Error> {
        let kids = key_ids(init_data_type, init_data)?;
        if kids.is_empty() {
            return Err(Error::NotSupported(String::from(
                "the initialization data names no key",
            )));
        }
        self.next_session += 1;
        let id = self.next_session;
        self.sessions.insert(id, Session { known: Vec::new() });
        let kids: Vec<String> = kids
            .iter()
            .map(|kid| format!("\"{}\"", base64url_encode(kid)))
            .collect();
        let message = format!("{{\"kids\":[{}],\"type\":\"temporary\"}}", kids.join(","));
        Ok((id, message.into_bytes()))
    }

    /// #dom-mediakeysession-update's CDM steps for a JWK Set license:
    /// the key IDs then known to the session, all usable.
    pub fn update(&mut self, session: u32, response: &[u8]) -> Result<Vec<Vec<u8>>, Error> {
        let Some(state) = self.sessions.get_mut(&session) else {
            return Err(Error::InvalidState);
        };
        let keys = parse_license(response)?;
        self.ring.insert(session, &keys);
        for (kid, _) in keys {
            if !state.known.contains(&kid) {
                state.known.push(kid);
            }
        }
        Ok(state.known.clone())
    }

    /// close() or remove(): the session's keys are destroyed.
    pub fn close(&mut self, session: u32) {
        if self.sessions.remove(&session).is_some() {
            self.ring.remove_session(session);
        }
    }

    pub fn remove(&mut self, session: u32) {
        if let Some(state) = self.sessions.get_mut(&session) {
            state.known.clear();
            self.ring.remove_session(session);
        }
    }
}

/// The key IDs of initialization data (#clear-key-behavior: "the request is
/// generated by extracting the key IDs from the sanitized init data").
pub fn key_ids(init_data_type: &str, init_data: &[u8]) -> Result<Vec<Vec<u8>>, Error> {
    let invalid = |what: &str| {
        Error::Type(format!(
            "invalid \"{init_data_type}\" initialization data: {what}"
        ))
    };
    match init_data_type {
        // Concatenated pssh boxes; Clear Key uses the Common SystemID's.
        "cenc" => {
            let mut at = 0;
            let mut found = None;
            while at < init_data.len() {
                let header = init_data
                    .get(at..at + 8)
                    .ok_or_else(|| invalid("truncated box"))?;
                let size =
                    u32::from_be_bytes([header[0], header[1], header[2], header[3]]) as usize;
                if &header[4..8] != b"pssh" || size < 32 || at + size > init_data.len() {
                    return Err(invalid("not a pssh box"));
                }
                let body = &init_data[at + 8..at + size];
                let version = body[0];
                if found.is_none() && body[4..20] == COMMON_SYSTEM_ID && version >= 1 {
                    let count =
                        u32::from_be_bytes([body[20], body[21], body[22], body[23]]) as usize;
                    if count > MAX_KEY_IDS || body.len() < 24 + count * 16 + 4 {
                        return Err(invalid("bad key ID count"));
                    }
                    found = Some(
                        (0..count)
                            .map(|i| body[24 + i * 16..40 + i * 16].to_vec())
                            .collect::<Vec<_>>(),
                    );
                }
                at += size;
            }
            found.ok_or_else(|| {
                Error::NotSupported(String::from("no pssh box with the Common SystemID"))
            })
        }
        // {"kids": [base64url, ...]}
        "keyids" => {
            let json: serde_json::Value =
                serde_json::from_slice(init_data).map_err(|_| invalid("not JSON"))?;
            let kids = json
                .get("kids")
                .and_then(|kids| kids.as_array())
                .ok_or_else(|| invalid("no \"kids\""))?;
            if kids.is_empty() || kids.len() > MAX_KEY_IDS {
                return Err(invalid("bad \"kids\" length"));
            }
            kids.iter()
                .map(|kid| {
                    kid.as_str()
                        .and_then(base64url_decode)
                        .filter(|kid| !kid.is_empty() && kid.len() <= MAX_KEY_ID_LEN)
                        .ok_or_else(|| invalid("bad key ID"))
                })
                .collect()
        }
        // A single ContentEncKeyID.
        "webm" => {
            if init_data.is_empty() || init_data.len() > MAX_KEY_ID_LEN {
                return Err(invalid("bad key ID"));
            }
            Ok(vec![init_data.to_vec()])
        }
        _ => Err(Error::NotSupported(format!(
            "initialization data type \"{init_data_type}\""
        ))),
    }
}

/// A JWK Set of symmetric AES-128 keys (RFC 7517; #clear-key-license-format).
fn parse_license(response: &[u8]) -> Result<super::Keys, Error> {
    let invalid = |what: &str| Error::Type(format!("invalid Clear Key license: {what}"));
    let json: serde_json::Value =
        serde_json::from_slice(response).map_err(|_| invalid("not JSON"))?;
    if let Some(kind) = json.get("type")
        && kind.as_str() != Some("temporary")
    {
        return Err(invalid("not a temporary license"));
    }
    let keys = json
        .get("keys")
        .and_then(|keys| keys.as_array())
        .ok_or_else(|| invalid("no \"keys\""))?;
    if keys.is_empty() || keys.len() > MAX_KEY_IDS {
        return Err(invalid("bad \"keys\" length"));
    }
    keys.iter()
        .map(|jwk| {
            if jwk.get("kty").and_then(|kty| kty.as_str()) != Some("oct") {
                return Err(invalid("a key is not \"oct\""));
            }
            let kid = jwk
                .get("kid")
                .and_then(|kid| kid.as_str())
                .and_then(base64url_decode)
                .filter(|kid| !kid.is_empty() && kid.len() <= MAX_KEY_ID_LEN)
                .ok_or_else(|| invalid("bad \"kid\""))?;
            let key: [u8; 16] = jwk
                .get("k")
                .and_then(|k| k.as_str())
                .and_then(base64url_decode)
                .and_then(|k| k.try_into().ok())
                .ok_or_else(|| invalid("a key is not 128 bits"))?;
            Ok((kid, key))
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The format registry's Common SystemID example: two key IDs.
    fn common_pssh() -> Vec<u8> {
        let mut pssh = vec![
            0x00, 0x00, 0x00, 0x44, b'p', b's', b's', b'h', 0x01, 0x00, 0x00, 0x00,
        ];
        pssh.extend_from_slice(&COMMON_SYSTEM_ID);
        pssh.extend_from_slice(&[0, 0, 0, 2]);
        pssh.extend_from_slice(b"0123456789012345ABCDEFGHIJKLMNOP");
        pssh.extend_from_slice(&[0, 0, 0, 0]);
        pssh
    }

    #[test]
    fn init_data_formats_yield_key_ids() {
        let kids = key_ids("cenc", &common_pssh()).unwrap();
        assert_eq!(
            kids,
            vec![b"0123456789012345".to_vec(), b"ABCDEFGHIJKLMNOP".to_vec()]
        );
        // Another system's pssh first is skipped.
        let mut other = common_pssh();
        other[12] = 0xed;
        let mut both = other.clone();
        both.extend_from_slice(&common_pssh());
        assert_eq!(key_ids("cenc", &both).unwrap().len(), 2);
        assert!(matches!(
            key_ids("cenc", &other),
            Err(Error::NotSupported(_))
        ));
        assert!(matches!(
            key_ids("cenc", &common_pssh()[..20]),
            Err(Error::Type(_))
        ));
        let keyids = br#"{"kids":["LwVHf8JLtPrv2GUXFW2v_A","0DdtU9od-Bh5L3xbv0Xf_A"]}"#;
        assert_eq!(key_ids("keyids", keyids).unwrap().len(), 2);
        assert!(matches!(
            key_ids("keyids", b"{\"kids\":[]}"),
            Err(Error::Type(_))
        ));
        assert_eq!(key_ids("webm", b"key").unwrap(), vec![b"key".to_vec()]);
        assert!(matches!(key_ids("sinf", b"x"), Err(Error::NotSupported(_))));
    }

    #[test]
    fn sessions_request_and_receive_keys() {
        let mut cdm = ClearKey::new();
        let keyids = br#"{"kids":["LwVHf8JLtPrv2GUXFW2v_A"]}"#;
        let (session, message) = cdm.generate_request("keyids", keyids).unwrap();
        assert_eq!(
            String::from_utf8(message).unwrap(),
            r#"{"kids":["LwVHf8JLtPrv2GUXFW2v_A"],"type":"temporary"}"#
        );
        let license = br#"{"keys":[{"kty":"oct","k":"tQ0bJVWb6b0KPL6KtZIy_A","kid":"LwVHf8JLtPrv2GUXFW2v_A"}],"type":"temporary"}"#;
        let known = cdm.update(session, license).unwrap();
        assert_eq!(
            known,
            vec![base64url_decode("LwVHf8JLtPrv2GUXFW2v_A").unwrap()]
        );
        let kid = base64url_decode("LwVHf8JLtPrv2GUXFW2v_A").unwrap();
        assert_eq!(
            cdm.ring().key(&kid).unwrap().to_vec(),
            base64url_decode("tQ0bJVWb6b0KPL6KtZIy_A").unwrap()
        );
        assert!(matches!(
            cdm.update(session, b"{\"keys\":[{\"kty\":\"RSA\"}]}"),
            Err(Error::Type(_))
        ));
        assert!(matches!(
            cdm.update(
                session,
                b"{\"keys\":[{\"kty\":\"oct\",\"k\":\"AA\",\"kid\":\"AA\"}]}"
            ),
            Err(Error::Type(_))
        ));
        cdm.close(session);
        assert_eq!(cdm.ring().key(&kid), None);
        assert_eq!(cdm.update(session, license), Err(Error::InvalidState));
    }
}
